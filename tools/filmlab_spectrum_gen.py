#!/usr/bin/env python3
"""Generate rtengine/filmspectrum.h: a smooth spectrum for every colour.

    python tools/filmlab_spectrum_gen.py            (run from the repository root)

Film Lab V6 lets each emulsion layer see a spectrum instead of three numbers.
A camera gives three numbers per pixel, so the spectrum has to be chosen: of
all the spectra that would produce a colour, this takes the smoothest one,
after Jakob and Hanika (2019),

    S(lambda) = 1/2 + y / (2 sqrt(1 + y^2)),   y = c0 x^2 + c1 x + c2,
    x = (lambda - 380) / 350,

which is how real surfaces tend to look: broad for pale colours, narrowing as
the colour saturates. The table holds (c0, c1, c2) on a grid of chromaticities
r = R/(R+G+B), g = G/(R+G+B) in the film stage's working primaries (ACES AP1),
for the colour scaled so its largest channel is 1/2. The film stage scales
the result back up, so one table serves every brightness.

The reference white is a 5500 K source (daylight film's balance) adapted to
AP1's white: a flat spectrum is exactly neutral.
"""
import re
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

ROOT = Path(__file__).resolve().parent.parent
N = 31                      # grid nodes per axis; node 10 is r = 1/3 (neutral)
LAMBDA = np.arange(380.0, 731.0, 10.0)
X = (LAMBDA - 380.0) / 350.0

XYZ_TO_AP1 = np.array([[1.6410233797, -0.3248032942, -0.2364246952],
                       [-0.6636628587, 1.6153315917, 0.0167563477],
                       [0.0117218943, -0.0082844420, 0.9883948585]])
AP1_WHITE = np.array([0.95265, 1.0, 1.00883])
BRADFORD = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])


def colour_matching():
    text = (ROOT / "rtengine" / "colortemp.cc").read_text(encoding="utf-8", errors="replace")
    start = text.index("cie_colour_match_jd2 = {")
    body = text[start:text.index("};", start)]
    rows = re.findall(r"\{\s*([-0-9.eE]+)\s*,\s*([-0-9.eE]+)\s*,\s*([-0-9.eE]+)\s*\}", body)
    table = np.array(rows, dtype=float)           # 350..830 nm, 5 nm
    wl = 350.0 + 5.0 * np.arange(len(table))
    return np.stack([np.interp(LAMBDA, wl, table[:, c]) for c in range(3)], axis=1)


def planck(temperature):
    lm = LAMBDA * 1e-9
    return (1.0 / lm ** 5) / (np.exp(6.626e-34 * 2.998e8 / (lm * 1.381e-23 * temperature)) - 1.0)


CMF = colour_matching()
WHITE = planck(5500.0)
white_xyz = (CMF * WHITE[:, None]).sum(axis=0)
white_xyz /= white_xyz[1]
adapt = np.linalg.inv(BRADFORD) @ np.diag((BRADFORD @ AP1_WHITE) / (BRADFORD @ white_xyz)) @ BRADFORD
# spectrum (reflectance under the reference white) -> AP1 RGB; flat 1.0 -> (1, 1, 1)
TO_RGB = (XYZ_TO_AP1 @ adapt @ (CMF * WHITE[:, None]).T) / (CMF[:, 1] * WHITE).sum()


def spectrum(c):
    y = c[0] * X * X + c[1] * X + c[2]
    return 0.5 + y / (2.0 * np.sqrt(1.0 + y * y))


def solve(target, start):
    best = None
    for guess in (start, np.zeros(3)):
        fit = least_squares(lambda c: TO_RGB @ spectrum(c) - target, guess, bounds=(-300.0, 300.0), xtol=1e-12, ftol=1e-12)
        if best is None or fit.cost < best.cost:
            best = fit
    return best.x, float(np.sqrt(2.0 * best.cost))


def literal(value):
    text = "%.5g" % value
    return (text if "." in text or "e" in text else text + ".0") + "f"


def main():
    assert np.allclose(TO_RGB @ np.ones(len(LAMBDA)), 1.0, atol=1e-9)
    coeff = np.full((N, N, 3), np.nan)
    error = np.zeros((N, N))
    neutral = (N - 1) // 3
    order = sorted(((i, j) for i in range(N) for j in range(N) if i + j <= N - 1),
                   key=lambda ij: (ij[0] - neutral) ** 2 + (ij[1] - neutral) ** 2)
    for i, j in order:
        chroma = np.array([i, j, N - 1 - i - j], dtype=float) / (N - 1)
        target = chroma * 0.5 / chroma.max()
        near = [(a, b) for a, b in ((i - 1, j), (i + 1, j), (i, j - 1), (i, j + 1), (i - 1, j + 1), (i + 1, j - 1))
                if 0 <= a < N and 0 <= b < N and not np.isnan(coeff[a, b, 0])]
        start = coeff[min(near, key=lambda ab: (ab[0] - neutral) ** 2 + (ab[1] - neutral) ** 2)] if near else np.zeros(3)
        coeff[i, j], error[i, j] = solve(target, start)
    # nodes beyond the r + g = 1 edge exist only so the lookup can interpolate across it
    for i in range(N):
        for j in range(N):
            if i + j > N - 1:
                over = i + j - (N - 1)
                a, b = i - (over + 1) // 2, j - over // 2
                coeff[i, j] = coeff[max(a, 0), max(b, 0)]
    inside = [(i, j) for i, j in order if min(i, j, N - 1 - i - j) >= 2]
    print(f"worst fit error, colours at least 2 steps inside the triangle: {max(error[i, j] for i, j in inside):.2e}", file=sys.stderr)
    print(f"worst fit error on the triangle's edge: {error.max():.3f} (those colours have no smooth spectrum)", file=sys.stderr)

    out = ["// Generated by tools/filmlab_spectrum_gen.py - do not edit by hand.",
           "// A smooth spectrum for every chromaticity; see that script for the model.",
           "#pragma once",
           "",
           "namespace rtengine {",
           "namespace filmspectrum {",
           "",
           f"constexpr int gridSize = {N};          // nodes per axis, r and g chromaticity from 0 to 1",
           f"constexpr int neutralNode = {neutral};       // r = g = 1/3",
           f"constexpr int wavelengths = {len(LAMBDA)};       // 380 to 730 nm in 10 nm steps",
           "constexpr float firstWavelength = 380.f;",
           "constexpr float wavelengthStep = 10.f;",
           "",
           "// The reference white (5500 K), relative power per wavelength.",
           "static const float white[wavelengths] = {",
           "    " + ", ".join(f"{v:.5f}f" for v in WHITE / WHITE.max()),
           "};",
           "",
           "// (c0, c1, c2) per node [r][g], for the colour scaled so its largest channel is 1/2.",
           "static const float coefficients[gridSize][gridSize][3] = {"]
    for i in range(N):
        out.append("    {")
        for j0 in range(0, N, 4):
            out.append("        " + " ".join("{%s, %s, %s}," % tuple(literal(v) for v in coeff[i, j])
                                             for j in range(j0, min(j0 + 4, N))))
        out.append("    },")
    out += ["};", "", "} // namespace filmspectrum", "} // namespace rtengine", ""]
    (ROOT / "rtengine" / "filmspectrum.h").write_bytes("\r\n".join(out).encode("ascii"))
    print("wrote rtengine/filmspectrum.h", file=sys.stderr)


if __name__ == "__main__":
    main()
